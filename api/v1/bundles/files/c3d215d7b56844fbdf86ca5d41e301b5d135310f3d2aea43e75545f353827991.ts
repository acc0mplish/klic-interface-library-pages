import VueForm1 from './components/vue-sfc/bar-chart/vertical.vue';
import VueForm2 from './components/vue-sfc/bar-chart/horizontal.vue';
import VueForm3 from './components/vue-sfc/bar-chart/grouped.vue';
import VueForm4 from './components/vue-sfc/bar-chart/stacked.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"vertical",name:"월별 세로 막대",component:VueForm1},{id:"horizontal",name:"분류별 가로 막대",component:VueForm2},{id:"grouped",name:"비교 막대",component:VueForm3},{id:"stacked",name:"구성 누적 막대",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Bar Chart"),h('p',"같은 기준에서 비교하는 항목별 값."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
