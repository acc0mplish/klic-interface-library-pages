import VueForm0 from './components/vue-sfc/empty-state/default.vue';
import VueForm1 from './components/vue-sfc/empty-state/first-project.vue';
import VueForm2 from './components/vue-sfc/empty-state/no-results.vue';
import VueForm3 from './components/vue-sfc/empty-state/permission.vue';
import VueForm4 from './components/vue-sfc/empty-state/all-done.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"first-project",name:"첫 프로젝트",component:VueForm1},{id:"no-results",name:"검색 결과 없음",component:VueForm2},{id:"permission",name:"접근 요청",component:VueForm3},{id:"all-done",name:"완료 상태",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Empty State"),h('p',"내용이 없을 때도 다음 행동을 제안."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
