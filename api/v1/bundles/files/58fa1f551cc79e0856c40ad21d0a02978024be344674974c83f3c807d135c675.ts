import VueForm0 from './components/vue-sfc/button-group/default.vue';
import VueForm1 from './components/vue-sfc/button-group/editor.vue';
import VueForm2 from './components/vue-sfc/button-group/split-publish.vue';
import VueForm3 from './components/vue-sfc/button-group/step-controls.vue';
import VueForm4 from './components/vue-sfc/button-group/bulk-actions.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"editor",name:"편집 도구",component:VueForm1},{id:"split-publish",name:"게시 분할 버튼",component:VueForm2},{id:"step-controls",name:"단계 이동 그룹",component:VueForm3},{id:"bulk-actions",name:"일괄 선택 동작",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Button Group"),h('p',"연관된 행동을 하나의 묶음으로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
