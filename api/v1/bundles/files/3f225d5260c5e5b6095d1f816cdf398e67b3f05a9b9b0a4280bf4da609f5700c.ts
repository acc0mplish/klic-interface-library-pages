import VueForm0 from './components/vue-sfc/message-actions/default.vue';
import VueForm1 from './components/vue-sfc/message-actions/versions.vue';
import VueForm2 from './components/vue-sfc/message-actions/technical.vue';
import VueForm3 from './components/vue-sfc/message-actions/feedback.vue';
import VueForm4 from './components/vue-sfc/message-actions/speech.vue';
const choices=[{id:"default",name:"기본 응답",component:VueForm0},{id:"versions",name:"여러 버전 비교",component:VueForm1},{id:"technical",name:"코드 설명",component:VueForm2},{id:"feedback",name:"편집 피드백",component:VueForm3},{id:"speech",name:"음성 읽기",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Message Actions"),h('p',"응답을 복사하고 버전과 피드백을 관리합니다."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
