const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"labeled",name:"아이콘과 이름",component:VueForm1},{id:"with-counts",name:"새 소식 개수",component:VueForm2},{id:"central-create",name:"가운데 생성 동작",component:VueForm3},{id:"floating",name:"떠 있는 탐색",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Bottom Navigation"),h('p',"모바일에서 손에 가까운 주요 메뉴."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
