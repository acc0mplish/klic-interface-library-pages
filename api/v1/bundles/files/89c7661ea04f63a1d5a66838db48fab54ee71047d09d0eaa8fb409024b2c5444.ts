import VueForm0 from './components/vue-sfc/toolbar/default.vue';
import VueForm1 from './components/vue-sfc/toolbar/text-editor.vue';
import VueForm2 from './components/vue-sfc/toolbar/document-view.vue';
import VueForm3 from './components/vue-sfc/toolbar/search-filter.vue';
import VueForm4 from './components/vue-sfc/toolbar/media-controls.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"text-editor",name:"문서 편집 도구",component:VueForm1},{id:"document-view",name:"문서 보기 도구",component:VueForm2},{id:"search-filter",name:"목록 도구",component:VueForm3},{id:"media-controls",name:"미디어 제어 도구",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Toolbar"),h('p',"현재 선택한 콘텐츠를 위한 도구."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
