import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/spinner/default.vue';
import VueForm1 from './components/vue-sfc/spinner/inline.vue';
import VueForm2 from './components/vue-sfc/spinner/panel.vue';
import VueForm3 from './components/vue-sfc/spinner/steps.vue';
import VueForm4 from './components/vue-sfc/spinner/cancelable.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"inline",name:"인라인 진행",component:VueForm1},{id:"panel",name:"패널 로딩",component:VueForm2},{id:"steps",name:"단계 안내 로딩",component:VueForm3},{id:"cancelable",name:"중단 가능한 처리",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Spinner"),h('p',"처리 중임을 알리는 회전 표시."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
