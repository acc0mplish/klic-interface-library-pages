import VueForm0 from './components/vue-sfc/notification/default.vue';
import VueForm1 from './components/vue-sfc/notification/mention.vue';
import VueForm2 from './components/vue-sfc/notification/invitation.vue';
import VueForm3 from './components/vue-sfc/notification/file-processing.vue';
import VueForm4 from './components/vue-sfc/notification/grouped-inbox.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"mention",name:"멘션 알림",component:VueForm1},{id:"invitation",name:"초대 알림",component:VueForm2},{id:"file-processing",name:"파일 처리 알림",component:VueForm3},{id:"grouped-inbox",name:"그룹 알림함",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Notification"),h('p',"읽음과 읽지 않음을 구별하는 소식."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
