import VueForm0 from './components/vue-sfc/timeline/default.vue';
import VueForm1 from './components/vue-sfc/timeline/activity.vue';
import VueForm2 from './components/vue-sfc/timeline/release.vue';
import VueForm3 from './components/vue-sfc/timeline/delivery.vue';
import VueForm4 from './components/vue-sfc/timeline/compact.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"activity",name:"협업 활동",component:VueForm1},{id:"release",name:"릴리스 기록",component:VueForm2},{id:"delivery",name:"요청 진행 기록",component:VueForm3},{id:"compact",name:"그룹형 날짜 기록",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Timeline"),h('p',"시간 순으로 읽는 활동과 기록."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
