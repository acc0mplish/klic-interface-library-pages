import VueForm1 from './components/vue-sfc/result/submitted.vue';
import VueForm2 from './components/vue-sfc/result/retry.vue';
import VueForm3 from './components/vue-sfc/result/review.vue';
import VueForm4 from './components/vue-sfc/result/summary.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"submitted",name:"제출 완료",component:VueForm1},{id:"retry",name:"재시도 결과",component:VueForm2},{id:"review",name:"승인 대기",component:VueForm3},{id:"summary",name:"처리 결과 요약",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Result"),h('p',"완료 여부와 다음 단계가 명확하게."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
