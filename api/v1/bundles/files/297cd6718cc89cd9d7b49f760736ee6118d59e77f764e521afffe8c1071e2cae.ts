import VueForm1 from './components/vue-sfc/select/grouped.vue';
import VueForm2 from './components/vue-sfc/select/sort.vue';
import VueForm3 from './components/vue-sfc/select/dependent.vue';
import VueForm4 from './components/vue-sfc/select/form-select.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"grouped",name:"그룹 선택",component:VueForm1},{id:"sort",name:"정렬 선택",component:VueForm2},{id:"dependent",name:"연결된 선택",component:VueForm3},{id:"form-select",name:"필수 선택",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Select"),h('p',"여러 가능성 중 가장 알맞은 하나."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
