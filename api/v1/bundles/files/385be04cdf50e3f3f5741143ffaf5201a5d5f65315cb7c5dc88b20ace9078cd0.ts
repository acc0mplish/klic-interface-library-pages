import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/textarea/default.vue';
import VueForm1 from './components/vue-sfc/textarea/counter.vue';
import VueForm2 from './components/vue-sfc/textarea/comment.vue';
import VueForm3 from './components/vue-sfc/textarea/feedback.vue';
import VueForm4 from './components/vue-sfc/textarea/readonly-note.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"counter",name:"글자 수 안내",component:VueForm1},{id:"comment",name:"댓글 작성",component:VueForm2},{id:"feedback",name:"피드백 양식",component:VueForm3},{id:"readonly-note",name:"읽기 전용 기록",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Textarea"),h('p',"긴 설명을 편안하게 작성하는 입력 영역."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
