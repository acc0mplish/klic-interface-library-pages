const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"profile",name:"프로필 미리 보기",component:VueForm1},{id:"media",name:"문서 커버 미리 보기",component:VueForm2},{id:"deployment",name:"배포 정보 미리 보기",component:VueForm3},{id:"release",name:"릴리스 미리 보기",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Hover Card"),h('p',"이름 옆에서 확인하는 사람의 맥락."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
