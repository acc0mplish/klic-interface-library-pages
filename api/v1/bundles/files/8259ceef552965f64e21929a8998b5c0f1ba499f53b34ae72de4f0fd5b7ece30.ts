const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"email-code",name:"이메일 인증",component:VueForm1},{id:"recovery",name:"복구 코드",component:VueForm2},{id:"sms",name:"문자 인증",component:VueForm3},{id:"backup",name:"보안 확인",component:VueForm4}];
