import VueForm1 from './components/vue-sfc/carousel/stories.vue';
import VueForm2 from './components/vue-sfc/carousel/testimonials.vue';
import VueForm3 from './components/vue-sfc/carousel/scroll-gallery.vue';
import VueForm4 from './components/vue-sfc/carousel/step-preview.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"stories",name:"콘텐츠 슬라이드",component:VueForm1},{id:"testimonials",name:"후기 회전",component:VueForm2},{id:"scroll-gallery",name:"스크롤 갤러리",component:VueForm3},{id:"step-preview",name:"과정 미리 보기",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Carousel"),h('p',"순서를 넘기며 살펴보는 이미지 모음."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
