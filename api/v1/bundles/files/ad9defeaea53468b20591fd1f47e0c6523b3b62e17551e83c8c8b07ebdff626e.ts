import VueForm0 from './components/vue-sfc/toast/default.vue';
import VueForm1 from './components/vue-sfc/toast/undo.vue';
import VueForm2 from './components/vue-sfc/toast/promise.vue';
import VueForm3 from './components/vue-sfc/toast/file.vue';
import VueForm4 from './components/vue-sfc/toast/invite.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"undo",name:"되돌리기 알림",component:VueForm1},{id:"promise",name:"비동기 결과 알림",component:VueForm2},{id:"file",name:"파일 결과 알림",component:VueForm3},{id:"invite",name:"사람 중심 알림",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Toast"),h('p',"흐름을 방해하지 않는 작은 피드백."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
