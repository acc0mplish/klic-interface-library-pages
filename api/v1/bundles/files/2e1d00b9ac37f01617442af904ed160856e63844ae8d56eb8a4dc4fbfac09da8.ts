import VueForm0 from './components/vue-sfc/range-slider/default.vue';
import VueForm1 from './components/vue-sfc/range-slider/price.vue';
import VueForm2 from './components/vue-sfc/range-slider/duration.vue';
import VueForm3 from './components/vue-sfc/range-slider/numeric-bounds.vue';
import VueForm4 from './components/vue-sfc/range-slider/preset-range.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"price",name:"가격 구간",component:VueForm1},{id:"duration",name:"시간 구간",component:VueForm2},{id:"numeric-bounds",name:"숫자 구간 입력",component:VueForm3},{id:"preset-range",name:"프리셋 구간",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Range Slider"),h('p',"최솟값과 최댓값 사이의 구간 선택."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
