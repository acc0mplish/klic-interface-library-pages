import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/alert/default.vue';
import VueForm1 from './components/vue-sfc/alert/actionable.vue';
import VueForm2 from './components/vue-sfc/alert/warning.vue';
import VueForm3 from './components/vue-sfc/alert/success-summary.vue';
import VueForm4 from './components/vue-sfc/alert/undo.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"actionable",name:"작업 안내",component:VueForm1},{id:"warning",name:"검토 필요 안내",component:VueForm2},{id:"success-summary",name:"완료 요약",component:VueForm3},{id:"undo",name:"실행 취소 안내",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Alert"),h('p',"현재 맥락에서 읽는 중요한 안내."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
