import VueForm0 from './components/vue-sfc/popover/default.vue';
import VueForm1 from './components/vue-sfc/popover/dimensions.vue';
import VueForm2 from './components/vue-sfc/popover/share.vue';
import VueForm3 from './components/vue-sfc/popover/preferences.vue';
import VueForm4 from './components/vue-sfc/popover/help.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"dimensions",name:"크기 빠른 설정",component:VueForm1},{id:"share",name:"공유 패널",component:VueForm2},{id:"preferences",name:"빠른 환경 설정",component:VueForm3},{id:"help",name:"작업 도움말",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Popover"),h('p',"지금의 맥락 안에서 필요한 정보만."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
