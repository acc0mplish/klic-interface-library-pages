const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"activity",name:"활동 스크롤",component:VueForm1},{id:"horizontal",name:"가로 자료 탐색",component:VueForm2},{id:"code-scroll",name:"코드 스크롤",component:VueForm3},{id:"roster",name:"긴 멤버 명단",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Scroll Area"),h('p',"넘치는 정보의 스크롤을 한곳에."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
