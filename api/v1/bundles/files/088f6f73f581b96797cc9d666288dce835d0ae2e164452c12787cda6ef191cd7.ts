import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/rating/default.vue';
import VueForm1 from './components/vue-sfc/rating/stars.vue';
import VueForm2 from './components/vue-sfc/rating/sentiment.vue';
import VueForm3 from './components/vue-sfc/rating/review.vue';
import VueForm4 from './components/vue-sfc/rating/breakdown.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"stars",name:"별점 평가",component:VueForm1},{id:"sentiment",name:"만족도 카드",component:VueForm2},{id:"review",name:"리뷰 작성",component:VueForm3},{id:"breakdown",name:"평점 분포",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Rating"),h('p',"점수마다 의미가 있는 평가."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
