import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/list/default.vue';
import VueForm1 from './components/vue-sfc/list/tasks.vue';
import VueForm2 from './components/vue-sfc/list/media.vue';
import VueForm3 from './components/vue-sfc/list/activity.vue';
import VueForm4 from './components/vue-sfc/list/settings.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"tasks",name:"작업 목록",component:VueForm1},{id:"media",name:"미디어 목록",component:VueForm2},{id:"activity",name:"활동 목록",component:VueForm3},{id:"settings",name:"설정 목록",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"List"),h('p',"서로 관련된 정보를 차례대로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
