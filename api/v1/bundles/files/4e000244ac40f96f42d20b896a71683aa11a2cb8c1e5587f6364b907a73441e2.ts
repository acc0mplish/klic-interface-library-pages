import VueForm0 from './components/vue-sfc/calendar/default.vue';
import VueForm1 from './components/vue-sfc/calendar/month-grid.vue';
import VueForm2 from './components/vue-sfc/calendar/agenda.vue';
import VueForm3 from './components/vue-sfc/calendar/week.vue';
import VueForm4 from './components/vue-sfc/calendar/booking.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"month-grid",name:"월간 일정",component:VueForm1},{id:"agenda",name:"일정 목록",component:VueForm2},{id:"week",name:"주간 계획",component:VueForm3},{id:"booking",name:"예약 일정",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Calendar"),h('p',"월별 날짜와 선택한 하루를 함께."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
