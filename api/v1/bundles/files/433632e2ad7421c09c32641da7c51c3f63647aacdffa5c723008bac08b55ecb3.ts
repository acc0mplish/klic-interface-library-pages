import VueForm1 from './components/vue-sfc/watermark/document.vue';
import VueForm2 from './components/vue-sfc/watermark/preview.vue';
import VueForm3 from './components/vue-sfc/watermark/owner.vue';
import VueForm4 from './components/vue-sfc/watermark/toggle-mark.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"document",name:"문서 식별",component:VueForm1},{id:"preview",name:"미리 보기 표시",component:VueForm2},{id:"owner",name:"소유자 식별",component:VueForm3},{id:"toggle-mark",name:"워터마크 제어",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Watermark"),h('p',"콘텐츠를 가리지 않는 문서 식별."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
