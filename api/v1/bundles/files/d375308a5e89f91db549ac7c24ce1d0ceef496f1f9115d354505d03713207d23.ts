import VueForm0 from './components/vue-sfc/autocomplete/default.vue';
import VueForm1 from './components/vue-sfc/autocomplete/people.vue';
import VueForm2 from './components/vue-sfc/autocomplete/timezone.vue';
import VueForm3 from './components/vue-sfc/autocomplete/command-search.vue';
import VueForm4 from './components/vue-sfc/autocomplete/create-option.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"people",name:"담당자 찾기",component:VueForm1},{id:"timezone",name:"시간대 찾기",component:VueForm2},{id:"command-search",name:"검색 가능한 목록",component:VueForm3},{id:"create-option",name:"새 항목 제안",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Autocomplete"),h('p',"자유로운 입력에 익숙한 후보를 더하기."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
