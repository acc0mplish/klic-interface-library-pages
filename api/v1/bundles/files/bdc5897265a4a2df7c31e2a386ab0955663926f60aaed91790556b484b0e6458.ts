const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"brand-preview",name:"브랜드 미리 보기",component:VueForm1},{id:"palette-table",name:"팔레트 편집",component:VueForm2},{id:"text-background",name:"본문과 배경",component:VueForm3},{id:"overlay",name:"커버 레이어",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Color Picker"),h('p',"회사 블루 안에서 고르는 강조색."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
