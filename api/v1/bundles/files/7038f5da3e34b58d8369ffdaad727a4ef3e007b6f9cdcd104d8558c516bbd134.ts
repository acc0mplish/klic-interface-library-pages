import VueForm1 from './components/vue-sfc/loading-overlay/content.vue';
import VueForm2 from './components/vue-sfc/loading-overlay/cancelable.vue';
import VueForm3 from './components/vue-sfc/loading-overlay/progress-overlay.vue';
import VueForm4 from './components/vue-sfc/loading-overlay/refreshable.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"content",name:"콘텐츠 덮개",component:VueForm1},{id:"cancelable",name:"중단 가능한 덮개",component:VueForm2},{id:"progress-overlay",name:"진행률 덮개",component:VueForm3},{id:"refreshable",name:"사용자 시작 로딩",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Loading Overlay"),h('p',"작업 중인 영역만 잠시 보호."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
