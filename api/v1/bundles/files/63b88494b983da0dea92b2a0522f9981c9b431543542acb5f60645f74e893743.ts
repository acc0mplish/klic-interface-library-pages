import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/context-menu/default.vue';
import VueForm1 from './components/vue-sfc/context-menu/document.vue';
import VueForm2 from './components/vue-sfc/context-menu/selection.vue';
import VueForm3 from './components/vue-sfc/context-menu/view.vue';
import VueForm4 from './components/vue-sfc/context-menu/image.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"document",name:"문서 컨텍스트",component:VueForm1},{id:"selection",name:"선택 항목 작업",component:VueForm2},{id:"view",name:"보기 옵션 메뉴",component:VueForm3},{id:"image",name:"이미지 컨텍스트",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Context Menu"),h('p',"선택한 항목에 맞는 바로가기 행동."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
