import VueForm0 from './components/vue-sfc/typography/default.vue';
import VueForm1 from './components/vue-sfc/typography/article.vue';
import VueForm2 from './components/vue-sfc/typography/data.vue';
import VueForm3 from './components/vue-sfc/typography/specimen.vue';
import VueForm4 from './components/vue-sfc/typography/editorial.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"article",name:"읽기 중심 본문",component:VueForm1},{id:"data",name:"숫자 타이포그래피",component:VueForm2},{id:"specimen",name:"타입 스케일",component:VueForm3},{id:"editorial",name:"편집형 카드",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Typography"),h('p',"읽기 순서가 선명한 글의 위계."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
