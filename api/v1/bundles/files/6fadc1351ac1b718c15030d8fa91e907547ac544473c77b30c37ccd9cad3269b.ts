import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/sheet/default.vue';
import VueForm1 from './components/vue-sfc/sheet/edit.vue';
import VueForm2 from './components/vue-sfc/sheet/confirm.vue';
import VueForm3 from './components/vue-sfc/sheet/scrollable.vue';
import VueForm4 from './components/vue-sfc/sheet/detail.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"edit",name:"편집 대화상자",component:VueForm1},{id:"confirm",name:"작업 확인",component:VueForm2},{id:"scrollable",name:"긴 내용 검토",component:VueForm3},{id:"detail",name:"상세 정보",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Sheet"),h('p',"맥락은 유지하고, 상세는 가까이."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
