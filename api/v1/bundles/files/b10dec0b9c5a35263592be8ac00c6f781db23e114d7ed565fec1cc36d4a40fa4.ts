import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/tree-select/default.vue';
import VueForm1 from './components/vue-sfc/tree-select/single-folder.vue';
import VueForm2 from './components/vue-sfc/tree-select/multi-folder.vue';
import VueForm3 from './components/vue-sfc/tree-select/popup-tree.vue';
import VueForm4 from './components/vue-sfc/tree-select/org-select.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"single-folder",name:"단일 폴더 선택",component:VueForm1},{id:"multi-folder",name:"복수 폴더 선택",component:VueForm2},{id:"popup-tree",name:"팝업 트리 선택",component:VueForm3},{id:"org-select",name:"조직 담당자 선택",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Tree Select"),h('p',"폴더 구조를 보며 하나를 선택."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
