const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"filter-grid",name:"검색 데이터 그리드",component:VueForm1},{id:"editable-grid",name:"수정 가능한 그리드",component:VueForm2},{id:"bulk-grid",name:"일괄 작업 그리드",component:VueForm3},{id:"comparison",name:"기능 비교 그리드",component:VueForm4}];
