const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"team",name:"팀 스택",component:VueForm1},{id:"roster",name:"멤버 명단",component:VueForm2},{id:"reviewers",name:"검토자 상태",component:VueForm3},{id:"invite",name:"멤버 추가 그룹",component:VueForm4}];
