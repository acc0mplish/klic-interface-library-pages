const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Avatar Group"),h('p',"함께하는 사람과 참여 인원 표시."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
