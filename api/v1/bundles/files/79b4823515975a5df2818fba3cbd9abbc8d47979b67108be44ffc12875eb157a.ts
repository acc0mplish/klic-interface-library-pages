import './fonts.css';
import VueForm0 from './components/vue-sfc/file-upload/default.vue';
import VueForm1 from './components/vue-sfc/file-upload/documents.vue';
import VueForm2 from './components/vue-sfc/file-upload/image.vue';
import VueForm3 from './components/vue-sfc/file-upload/inline.vue';
import VueForm4 from './components/vue-sfc/file-upload/drop-target.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"documents",name:"문서 첨부",component:VueForm1},{id:"image",name:"이미지 선택",component:VueForm2},{id:"inline",name:"인라인 첨부",component:VueForm3},{id:"drop-target",name:"드래그 영역",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"File Upload"),h('p',"선택한 파일의 이름과 크기를 확인."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
