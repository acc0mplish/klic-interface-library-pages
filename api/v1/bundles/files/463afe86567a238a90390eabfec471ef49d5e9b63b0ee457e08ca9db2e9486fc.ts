const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"identity",name:"프로필 정체성",component:VueForm1},{id:"stacked",name:"담당자 스택",component:VueForm2},{id:"menu",name:"계정 메뉴",component:VueForm3},{id:"editable",name:"프로필 편집",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Avatar"),h('p',"같은 사람을 어디서나 같은 얼굴로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
