import VueForm0 from './components/vue-sfc/toggle-group/default.vue';
import VueForm1 from './components/vue-sfc/toggle-group/vertical-toolbar.vue';
import VueForm2 from './components/vue-sfc/toggle-group/topic-filters.vue';
import VueForm3 from './components/vue-sfc/toggle-group/display-options.vue';
import VueForm4 from './components/vue-sfc/toggle-group/text-controls.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"vertical-toolbar",name:"세로 편집 도구",component:VueForm1},{id:"topic-filters",name:"주제 필터",component:VueForm2},{id:"display-options",name:"정보 표시 옵션",component:VueForm3},{id:"text-controls",name:"문장 강조 도구",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Toggle Group"),h('p',"여러 표시 옵션을 독립적으로 선택."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
