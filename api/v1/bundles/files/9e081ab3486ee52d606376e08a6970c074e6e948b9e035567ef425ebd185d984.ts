import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/card/default.vue';
import VueForm1 from './components/vue-sfc/card/media.vue';
import VueForm2 from './components/vue-sfc/card/project.vue';
import VueForm3 from './components/vue-sfc/card/pricing.vue';
import VueForm4 from './components/vue-sfc/card/profile.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"media",name:"이미지 콘텐츠 카드",component:VueForm1},{id:"project",name:"프로젝트 요약 카드",component:VueForm2},{id:"pricing",name:"가격 비교 카드",component:VueForm3},{id:"profile",name:"사람 중심 카드",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Card"),h('p',"관련된 정보를 하나의 맥락으로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
