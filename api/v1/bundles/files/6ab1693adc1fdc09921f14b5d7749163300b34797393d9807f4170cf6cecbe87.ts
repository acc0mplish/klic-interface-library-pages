import VueForm0 from './components/vue-sfc/time-picker/default.vue';
import VueForm1 from './components/vue-sfc/time-picker/meeting.vue';
import VueForm2 from './components/vue-sfc/time-picker/bounds.vue';
import VueForm3 from './components/vue-sfc/time-picker/deadline.vue';
import VueForm4 from './components/vue-sfc/time-picker/availability.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"meeting",name:"미팅 일정",component:VueForm1},{id:"bounds",name:"업무 구간",component:VueForm2},{id:"deadline",name:"마감 지정",component:VueForm3},{id:"availability",name:"가능 시간 제출",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Time Picker"),h('p',"시·분 단위로 약속의 시간을 정하기."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
