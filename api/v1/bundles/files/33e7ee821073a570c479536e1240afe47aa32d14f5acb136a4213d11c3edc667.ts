import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/decision-inbox/default.vue';
import VueForm1 from './components/vue-sfc/decision-inbox/release.vue';
import VueForm2 from './components/vue-sfc/decision-inbox/permission.vue';
import VueForm3 from './components/vue-sfc/decision-inbox/editorial.vue';
import VueForm4 from './components/vue-sfc/decision-inbox/conflict.vue';
const choices=[{id:"default",name:"검토가 필요한 결정",component:VueForm0},{id:"release",name:"출시 전 승인",component:VueForm1},{id:"permission",name:"권한 요청",component:VueForm2},{id:"editorial",name:"콘텐츠 편집",component:VueForm3},{id:"conflict",name:"데이터 충돌 해결",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Decision Inbox"),h('p',"답변을 기다리는 결정을 차례로 검토합니다."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
