import VueForm1 from './components/vue-sfc/form/profile.vue';
import VueForm2 from './components/vue-sfc/form/contact.vue';
import VueForm3 from './components/vue-sfc/form/preferences.vue';
import VueForm4 from './components/vue-sfc/form/invitation.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"profile",name:"프로필 양식",component:VueForm1},{id:"contact",name:"문의 양식",component:VueForm2},{id:"preferences",name:"환경 설정 양식",component:VueForm3},{id:"invitation",name:"멤버 초대 양식",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Form"),h('p',"필드와 검증을 하나의 제출 흐름으로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
