import VueForm0 from './components/vue-sfc/slider/default.vue';
import VueForm1 from './components/vue-sfc/slider/volume.vue';
import VueForm2 from './components/vue-sfc/slider/zoom.vue';
import VueForm3 from './components/vue-sfc/slider/allocation.vue';
import VueForm4 from './components/vue-sfc/slider/opacity.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"volume",name:"음량 조절",component:VueForm1},{id:"zoom",name:"확대 비율",component:VueForm2},{id:"allocation",name:"리소스 배분",component:VueForm3},{id:"opacity",name:"투명도 미리 보기",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Slider"),h('p',"연속된 값을 직관적으로 조절하세요."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
