import VueForm0 from './components/vue-sfc/tool-call-card/default.vue';
import VueForm1 from './components/vue-sfc/tool-call-card/retry.vue';
import VueForm2 from './components/vue-sfc/tool-call-card/running.vue';
import VueForm3 from './components/vue-sfc/tool-call-card/payload.vue';
import VueForm4 from './components/vue-sfc/tool-call-card/group.vue';
const choices=[{id:"default",name:"검색 결과",component:VueForm0},{id:"retry",name:"실패와 복구",component:VueForm1},{id:"running",name:"실행 중인 작업",component:VueForm2},{id:"payload",name:"긴 JSON 결과",component:VueForm3},{id:"group",name:"도구 실행 그룹",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Tool Call Card"),h('p',"에이전트의 도구 호출과 결과를 투명하게 보여줍니다."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
