import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/field/default.vue';
import VueForm1 from './components/vue-sfc/field/horizontal.vue';
import VueForm2 from './components/vue-sfc/field/choice-field.vue';
import VueForm3 from './components/vue-sfc/field/validation.vue';
import VueForm4 from './components/vue-sfc/field/compound.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"horizontal",name:"수평 필드",component:VueForm1},{id:"choice-field",name:"선택 카드 필드",component:VueForm2},{id:"validation",name:"검증 안내 필드",component:VueForm3},{id:"compound",name:"복합 연락처 필드",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Field"),h('p',"레이블, 입력, 도움말을 하나로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
