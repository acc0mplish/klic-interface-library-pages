import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/code-block/default.vue';
import VueForm1 from './components/vue-sfc/code-block/filename.vue';
import VueForm2 from './components/vue-sfc/code-block/language-tabs.vue';
import VueForm3 from './components/vue-sfc/code-block/diff.vue';
import VueForm4 from './components/vue-sfc/code-block/terminal.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"filename",name:"파일 코드",component:VueForm1},{id:"language-tabs",name:"언어별 코드",component:VueForm2},{id:"diff",name:"변경 비교",component:VueForm3},{id:"terminal",name:"터미널 안내",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Code Block"),h('p',"읽고 복사할 수 있는 코드 조각."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
