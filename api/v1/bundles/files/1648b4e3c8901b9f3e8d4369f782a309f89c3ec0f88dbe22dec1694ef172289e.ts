const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"vertical-account",name:"세로 계정 탭",component:VueForm1},{id:"project",name:"프로젝트 작업 탭",component:VueForm2},{id:"preview-code",name:"미리 보기와 코드",component:VueForm3},{id:"metrics",name:"통계 기간 탭",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Tabs"),h('p',"같은 공간에 담긴 서로 다른 관점."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
