import VueForm1 from './components/vue-sfc/link/external.vue';
import VueForm2 from './components/vue-sfc/link/card-link.vue';
import VueForm3 from './components/vue-sfc/link/download-data.vue';
import VueForm4 from './components/vue-sfc/link/inline-reference.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"external",name:"외부 문서 링크",component:VueForm1},{id:"card-link",name:"설명형 링크 카드",component:VueForm2},{id:"download-data",name:"데이터 링크",component:VueForm3},{id:"inline-reference",name:"본문 참고 링크",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Link"),h('p',"이동할 목적지를 분명하게 알리기."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
