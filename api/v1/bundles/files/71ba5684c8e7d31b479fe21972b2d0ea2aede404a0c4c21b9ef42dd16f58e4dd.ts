const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"columns",name:"열형 계층 선택",component:VueForm1},{id:"popover-cascade",name:"팝업 계층 선택",component:VueForm2},{id:"form-cascade",name:"문의 분류 양식",component:VueForm3},{id:"summary-cascade",name:"선택 경로 요약",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Cascader"),h('p',"상위 선택에 맞춰 바뀌는 하위 목록."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
