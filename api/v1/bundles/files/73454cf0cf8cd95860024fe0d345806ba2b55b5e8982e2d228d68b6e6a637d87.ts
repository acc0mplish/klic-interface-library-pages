import VueForm0 from './components/vue-sfc/powershell-terminal/default.vue';
const choices=[{id:"default",name:"터미널 창",component:VueForm0}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Windows PowerShell"),h('p',"Windows Terminal 탭과 창 제어를 갖춘 PowerShell 콘솔 화면."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
