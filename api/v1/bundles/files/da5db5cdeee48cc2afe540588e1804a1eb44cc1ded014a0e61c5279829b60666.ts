import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/popconfirm/default.vue';
import VueForm1 from './components/vue-sfc/popconfirm/delete-row.vue';
import VueForm2 from './components/vue-sfc/popconfirm/reset.vue';
import VueForm3 from './components/vue-sfc/popconfirm/leave.vue';
import VueForm4 from './components/vue-sfc/popconfirm/overwrite.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"delete-row",name:"행 삭제 확인",component:VueForm1},{id:"reset",name:"필터 초기화 확인",component:VueForm2},{id:"leave",name:"프로젝트 나가기",component:VueForm3},{id:"overwrite",name:"덮어쓰기 확인",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Popconfirm"),h('p',"행동 근처에서 확인하고 실행하기."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
