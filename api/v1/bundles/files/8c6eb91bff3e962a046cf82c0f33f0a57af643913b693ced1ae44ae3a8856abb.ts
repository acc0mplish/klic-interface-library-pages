const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"workspace",name:"워크스페이스 사이드바",component:VueForm1},{id:"settings",name:"설정 사이드바",component:VueForm2},{id:"collapsible",name:"접이식 사이드바",component:VueForm3},{id:"inbox",name:"받은 편지함",component:VueForm4}];
