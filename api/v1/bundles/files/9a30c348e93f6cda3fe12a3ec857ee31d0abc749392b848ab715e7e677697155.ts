import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/breadcrumb/default.vue';
import VueForm1 from './components/vue-sfc/breadcrumb/path.vue';
import VueForm2 from './components/vue-sfc/breadcrumb/collapsed.vue';
import VueForm3 from './components/vue-sfc/breadcrumb/with-icon.vue';
import VueForm4 from './components/vue-sfc/breadcrumb/back-trail.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"path",name:"문서 경로",component:VueForm1},{id:"collapsed",name:"축약 경로",component:VueForm2},{id:"with-icon",name:"아이콘 경로",component:VueForm3},{id:"back-trail",name:"뒤로와 위치",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Breadcrumb"),h('p',"현재 위치까지 이어지는 길."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
