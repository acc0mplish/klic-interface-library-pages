import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/badge/default.vue';
import VueForm1 from './components/vue-sfc/badge/status.vue';
import VueForm2 from './components/vue-sfc/badge/removable.vue';
import VueForm3 from './components/vue-sfc/badge/selectable.vue';
import VueForm4 from './components/vue-sfc/badge/metadata.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"status",name:"상태와 맥락",component:VueForm1},{id:"removable",name:"삭제 가능한 필터",component:VueForm2},{id:"selectable",name:"선택형 주제",component:VueForm3},{id:"metadata",name:"설명형 메타데이터",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Badge"),h('p',"상태와 맥락을 짧고 정확하게."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
