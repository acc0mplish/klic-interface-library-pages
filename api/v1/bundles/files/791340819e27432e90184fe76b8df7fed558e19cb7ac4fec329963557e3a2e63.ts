const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"files",name:"파일 계층",component:VueForm1},{id:"organization",name:"조직 구조",component:VueForm2},{id:"category-select",name:"분류 선택",component:VueForm3},{id:"permission-tree",name:"권한 계층",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Tree"),h('p',"펼쳐보며 이해하는 파일 구조."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
