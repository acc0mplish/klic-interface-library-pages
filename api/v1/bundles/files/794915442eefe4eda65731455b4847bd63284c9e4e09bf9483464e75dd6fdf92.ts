import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/mentions/default.vue';
import VueForm1 from './components/vue-sfc/mentions/person.vue';
import VueForm2 from './components/vue-sfc/mentions/team.vue';
import VueForm3 from './components/vue-sfc/mentions/comment-thread.vue';
import VueForm4 from './components/vue-sfc/mentions/issue.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"person",name:"담당자 멘션",component:VueForm1},{id:"team",name:"팀 멘션",component:VueForm2},{id:"comment-thread",name:"대화 속 멘션",component:VueForm3},{id:"issue",name:"이슈 연결",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Mentions"),h('p',"작성 중인 문장에 담당자를 연결."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
