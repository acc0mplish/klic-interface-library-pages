const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"leading-icon",name:"아이콘 동작",component:VueForm1},{id:"split-action",name:"분할 실행",component:VueForm2},{id:"confirmation",name:"확인형 동작",component:VueForm3},{id:"icon-tools",name:"아이콘 단독 작업",component:VueForm4}];
