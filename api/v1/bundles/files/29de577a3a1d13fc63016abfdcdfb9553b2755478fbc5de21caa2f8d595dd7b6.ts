import './fonts.css';
import VueForm0 from './components/vue-sfc/number-input/default.vue';
import VueForm1 from './components/vue-sfc/number-input/quantity.vue';
import VueForm2 from './components/vue-sfc/number-input/budget.vue';
import VueForm3 from './components/vue-sfc/number-input/dimension.vue';
import VueForm4 from './components/vue-sfc/number-input/threshold.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"quantity",name:"상품 수량",component:VueForm1},{id:"budget",name:"예산 조절",component:VueForm2},{id:"dimension",name:"가로 세로 입력",component:VueForm3},{id:"threshold",name:"알림 임계값",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Number Input"),h('p',"직접 입력과 증감 버튼을 함께."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
