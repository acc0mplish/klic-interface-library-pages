const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"wizard",name:"설정 마법사",component:VueForm1},{id:"delivery",name:"처리 단계",component:VueForm2},{id:"onboarding",name:"시작 체크리스트",component:VueForm3},{id:"review",name:"검토 단계 요약",component:VueForm4}];
