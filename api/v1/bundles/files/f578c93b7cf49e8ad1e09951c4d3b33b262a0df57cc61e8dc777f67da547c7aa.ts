import VueForm1 from './components/vue-sfc/banner/announcement.vue';
import VueForm2 from './components/vue-sfc/banner/maintenance.vue';
import VueForm3 from './components/vue-sfc/banner/dismissible.vue';
import VueForm4 from './components/vue-sfc/banner/quota.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"announcement",name:"업데이트 공지",component:VueForm1},{id:"maintenance",name:"점검 일정",component:VueForm2},{id:"dismissible",name:"닫을 수 있는 안내",component:VueForm3},{id:"quota",name:"사용량 안내",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Banner"),h('p',"화면 전체에 관련된 소식을 한 줄로."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
