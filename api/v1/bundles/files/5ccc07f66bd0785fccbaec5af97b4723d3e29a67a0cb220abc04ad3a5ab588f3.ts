import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/collapsible/default.vue';
import VueForm1 from './components/vue-sfc/collapsible/advanced.vue';
import VueForm2 from './components/vue-sfc/collapsible/activity.vue';
import VueForm3 from './components/vue-sfc/collapsible/code.vue';
import VueForm4 from './components/vue-sfc/collapsible/members.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"advanced",name:"고급 설정",component:VueForm1},{id:"activity",name:"최근 활동",component:VueForm2},{id:"code",name:"코드 상세",component:VueForm3},{id:"members",name:"멤버 확장",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Collapsible"),h('p',"하나의 보조 영역을 열고 닫기."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
