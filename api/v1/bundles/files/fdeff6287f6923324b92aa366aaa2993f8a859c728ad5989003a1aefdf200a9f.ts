import VueForm0 from './components/vue-sfc/descriptions/default.vue';
import VueForm1 from './components/vue-sfc/descriptions/project.vue';
import VueForm2 from './components/vue-sfc/descriptions/account.vue';
import VueForm3 from './components/vue-sfc/descriptions/billing.vue';
import VueForm4 from './components/vue-sfc/descriptions/technical.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"project",name:"프로젝트 속성",component:VueForm1},{id:"account",name:"계정 상세",component:VueForm2},{id:"billing",name:"청구 정보",component:VueForm3},{id:"technical",name:"기술 속성",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Descriptions"),h('p',"이름과 값으로 정리한 속성 정보."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
