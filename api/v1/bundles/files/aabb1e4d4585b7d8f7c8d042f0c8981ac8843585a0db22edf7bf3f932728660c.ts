import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/toggle/default.vue';
import VueForm1 from './components/vue-sfc/toggle/bookmark.vue';
import VueForm2 from './components/vue-sfc/toggle/icon-only.vue';
import VueForm3 from './components/vue-sfc/toggle/notification-card.vue';
import VueForm4 from './components/vue-sfc/toggle/reaction.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"bookmark",name:"문서 북마크",component:VueForm1},{id:"icon-only",name:"아이콘 토글",component:VueForm2},{id:"notification-card",name:"알림 토글 카드",component:VueForm3},{id:"reaction",name:"반응 토글",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Toggle"),h('p',"눌린 상태가 남는 독립적인 버튼."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
