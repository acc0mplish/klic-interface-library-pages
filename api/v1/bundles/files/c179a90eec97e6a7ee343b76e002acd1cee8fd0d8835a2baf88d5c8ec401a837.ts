import VueForm2 from './components/vue-sfc/skeleton/media-card.vue';
import VueForm3 from './components/vue-sfc/skeleton/table.vue';
import VueForm4 from './components/vue-sfc/skeleton/form.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"profile",name:"프로필 로딩",component:VueForm1},{id:"media-card",name:"미디어 카드 로딩",component:VueForm2},{id:"table",name:"표 로딩",component:VueForm3},{id:"form",name:"폼 로딩",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Skeleton"),h('p',"불러올 콘텐츠의 구조를 먼저."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
