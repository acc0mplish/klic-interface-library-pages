import VueForm0 from './components/vue-sfc/accordion/default.vue';
import VueForm1 from './components/vue-sfc/accordion/faq.vue';
import VueForm2 from './components/vue-sfc/accordion/settings-sections.vue';
import VueForm3 from './components/vue-sfc/accordion/outline.vue';
import VueForm4 from './components/vue-sfc/accordion/order-detail.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"faq",name:"자주 묻는 질문",component:VueForm1},{id:"settings-sections",name:"설정 섹션",component:VueForm2},{id:"outline",name:"문서 개요",component:VueForm3},{id:"order-detail",name:"주문 상세",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Accordion"),h('p',"복잡한 내용은 필요한 만큼 펼쳐서."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
