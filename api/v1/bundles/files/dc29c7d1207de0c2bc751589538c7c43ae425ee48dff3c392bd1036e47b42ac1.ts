import VueForm1 from './components/vue-sfc/command/project-switch.vue';
import VueForm2 from './components/vue-sfc/command/actions.vue';
import VueForm3 from './components/vue-sfc/command/people.vue';
import VueForm4 from './components/vue-sfc/command/dialog-command.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"project-switch",name:"프로젝트 전환",component:VueForm1},{id:"actions",name:"명령 팔레트",component:VueForm2},{id:"people",name:"팀원 검색",component:VueForm3},{id:"dialog-command",name:"대화형 검색",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Command"),h('p',"이름으로 빠르게 찾고 실행하는 명령."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
