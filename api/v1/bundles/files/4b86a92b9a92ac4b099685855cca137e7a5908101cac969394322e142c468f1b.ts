import VueForm0 from './components/vue-sfc/input-group/default.vue';
import VueForm1 from './components/vue-sfc/input-group/domain.vue';
import VueForm2 from './components/vue-sfc/input-group/budget.vue';
import VueForm3 from './components/vue-sfc/input-group/search-action.vue';
import VueForm4 from './components/vue-sfc/input-group/composer.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"domain",name:"주소 접두사",component:VueForm1},{id:"budget",name:"단위와 금액",component:VueForm2},{id:"search-action",name:"검색 실행 그룹",component:VueForm3},{id:"composer",name:"메시지 작성 그룹",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Input Group"),h('p',"주소의 앞뒤 맥락을 입력에 연결."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
