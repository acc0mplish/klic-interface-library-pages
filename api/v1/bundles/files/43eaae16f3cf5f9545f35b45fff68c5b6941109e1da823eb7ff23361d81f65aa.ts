import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/dropdown-menu/default.vue';
import VueForm1 from './components/vue-sfc/dropdown-menu/file-actions.vue';
import VueForm2 from './components/vue-sfc/dropdown-menu/checks.vue';
import VueForm3 from './components/vue-sfc/dropdown-menu/radio.vue';
import VueForm4 from './components/vue-sfc/dropdown-menu/account.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"file-actions",name:"문서 작업 메뉴",component:VueForm1},{id:"checks",name:"체크 메뉴",component:VueForm2},{id:"radio",name:"단일 선택 메뉴",component:VueForm3},{id:"account",name:"계정 드롭다운",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Dropdown Menu"),h('p',"한곳에 모아둔 관련 행동."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
