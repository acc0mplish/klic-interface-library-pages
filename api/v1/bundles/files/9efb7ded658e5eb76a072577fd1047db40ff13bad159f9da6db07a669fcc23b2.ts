import VueForm0 from './components/vue-sfc/progress/default.vue';
import VueForm1 from './components/vue-sfc/progress/task.vue';
import VueForm2 from './components/vue-sfc/progress/segmented.vue';
import VueForm3 from './components/vue-sfc/progress/upload-control.vue';
import VueForm4 from './components/vue-sfc/progress/quota.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"task",name:"작업 진행",component:VueForm1},{id:"segmented",name:"단계별 진행",component:VueForm2},{id:"upload-control",name:"진행 제어",component:VueForm3},{id:"quota",name:"제한 사용량",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Progress"),h('p',"기다림에도 알 수 있는 다음 단계."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
