import VueForm0 from './components/vue-sfc/alert-dialog/default.vue';
import VueForm1 from './components/vue-sfc/alert-dialog/discard.vue';
import VueForm2 from './components/vue-sfc/alert-dialog/remove-member.vue';
import VueForm3 from './components/vue-sfc/alert-dialog/archive.vue';
import VueForm4 from './components/vue-sfc/alert-dialog/publish.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"discard",name:"수정 내용 폐기",component:VueForm1},{id:"remove-member",name:"멤버 제거 확인",component:VueForm2},{id:"archive",name:"프로젝트 보관 확인",component:VueForm3},{id:"publish",name:"공개 전 확인",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Alert Dialog"),h('p',"되돌리기 어려운 행동을 다시 확인."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
