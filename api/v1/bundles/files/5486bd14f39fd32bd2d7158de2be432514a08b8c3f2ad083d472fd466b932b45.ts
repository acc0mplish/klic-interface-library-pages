const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"report-range",name:"보고서 기간",component:VueForm1},{id:"booking-range",name:"예약 기간",component:VueForm2},{id:"comparison-range",name:"비교 기간",component:VueForm3},{id:"project-range",name:"프로젝트 구간",component:VueForm4}];
