import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/menubar/default.vue';
import VueForm1 from './components/vue-sfc/menubar/document.vue';
import VueForm2 from './components/vue-sfc/menubar/view-options.vue';
import VueForm3 from './components/vue-sfc/menubar/radio-settings.vue';
import VueForm4 from './components/vue-sfc/menubar/icon-commands.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"document",name:"문서 메뉴바",component:VueForm1},{id:"view-options",name:"보기 설정 메뉴바",component:VueForm2},{id:"radio-settings",name:"정렬 설정 메뉴바",component:VueForm3},{id:"icon-commands",name:"아이콘 명령 메뉴바",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Menubar"),h('p',"자주 쓰는 명령을 주제별로 묶기."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
