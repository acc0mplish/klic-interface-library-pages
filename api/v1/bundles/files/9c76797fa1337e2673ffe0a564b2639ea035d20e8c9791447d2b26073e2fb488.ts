const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"document-filter",name:"문서 필터",component:VueForm1},{id:"command-search",name:"명령 검색",component:VueForm2},{id:"advanced",name:"상세 검색",component:VueForm3},{id:"with-history",name:"검색 기록",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Search Input"),h('p',"실제 목록과 연결되는 빠른 검색."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
