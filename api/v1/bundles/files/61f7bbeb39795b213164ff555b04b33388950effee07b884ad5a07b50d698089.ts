import VueForm1 from './components/vue-sfc/sparkline/revenue.vue';
import VueForm2 from './components/vue-sfc/sparkline/comparison.vue';
import VueForm3 from './components/vue-sfc/sparkline/table-trends.vue';
import VueForm4 from './components/vue-sfc/sparkline/threshold.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"revenue",name:"매출 추세 지표",component:VueForm1},{id:"comparison",name:"지표 목록",component:VueForm2},{id:"table-trends",name:"표 안 추세",component:VueForm3},{id:"threshold",name:"기준선 추세",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Sparkline"),h('p',"수치 옆에서 읽는 짧은 추세."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
