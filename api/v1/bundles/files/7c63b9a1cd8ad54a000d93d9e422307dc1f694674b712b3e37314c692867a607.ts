import VueForm0 from './components/vue-sfc/dialog/default.vue';
import VueForm1 from './components/vue-sfc/dialog/edit.vue';
import VueForm2 from './components/vue-sfc/dialog/confirm.vue';
import VueForm3 from './components/vue-sfc/dialog/scrollable.vue';
import VueForm4 from './components/vue-sfc/dialog/detail.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"edit",name:"편집 대화상자",component:VueForm1},{id:"confirm",name:"작업 확인",component:VueForm2},{id:"scrollable",name:"긴 내용 검토",component:VueForm3},{id:"detail",name:"상세 정보",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Dialog"),h('p',"중요한 순간, 필요한 대화에 집중."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
