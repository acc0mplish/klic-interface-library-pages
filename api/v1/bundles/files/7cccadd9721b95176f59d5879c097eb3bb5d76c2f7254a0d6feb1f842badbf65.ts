import VueForm0 from './components/vue-sfc/pagination/default.vue';
import VueForm1 from './components/vue-sfc/pagination/numbered.vue';
import VueForm2 from './components/vue-sfc/pagination/compact.vue';
import VueForm3 from './components/vue-sfc/pagination/load-more.vue';
import VueForm4 from './components/vue-sfc/pagination/page-size.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"numbered",name:"번호 페이지",component:VueForm1},{id:"compact",name:"간단 페이지",component:VueForm2},{id:"load-more",name:"더 불러오기",component:VueForm3},{id:"page-size",name:"페이지 크기",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Pagination"),h('p',"목록의 앞뒤와 현재 페이지를 함께."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
