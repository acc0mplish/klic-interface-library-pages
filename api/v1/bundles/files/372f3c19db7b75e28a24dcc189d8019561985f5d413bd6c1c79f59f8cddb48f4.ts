import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/switch/default.vue';
import VueForm1 from './components/vue-sfc/switch/description-row.vue';
import VueForm2 from './components/vue-sfc/switch/choice-card.vue';
import VueForm3 from './components/vue-sfc/switch/grouped.vue';
import VueForm4 from './components/vue-sfc/switch/form-setting.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"description-row",name:"설명형 설정 행",component:VueForm1},{id:"choice-card",name:"전체 설정 카드",component:VueForm2},{id:"grouped",name:"그룹별 스위치",component:VueForm3},{id:"form-setting",name:"저장형 스위치",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Switch"),h('p',"설정의 상태를 가볍게 전환하세요."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
