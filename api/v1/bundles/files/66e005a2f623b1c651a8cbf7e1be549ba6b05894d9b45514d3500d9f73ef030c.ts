import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/tooltip/default.vue';
import VueForm1 from './components/vue-sfc/tooltip/shortcut.vue';
import VueForm2 from './components/vue-sfc/tooltip/verified.vue';
import VueForm3 from './components/vue-sfc/tooltip/role.vue';
import VueForm4 from './components/vue-sfc/tooltip/metadata.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"shortcut",name:"단축키 설명",component:VueForm1},{id:"verified",name:"검증 상태 설명",component:VueForm2},{id:"role",name:"권한 범위 설명",component:VueForm3},{id:"metadata",name:"파일 속성 설명",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Tooltip"),h('p',"포커스와 호버로 확인하는 짧은 도움말."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
