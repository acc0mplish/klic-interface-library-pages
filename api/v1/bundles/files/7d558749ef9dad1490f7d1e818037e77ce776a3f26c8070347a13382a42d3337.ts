import VueForm0 from './components/vue-sfc/table/default.vue';
import VueForm1 from './components/vue-sfc/table/team.vue';
import VueForm2 from './components/vue-sfc/table/invoices.vue';
import VueForm3 from './components/vue-sfc/table/selectable.vue';
import VueForm4 from './components/vue-sfc/table/actions.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"team",name:"팀 명단 표",component:VueForm1},{id:"invoices",name:"청구 내역 표",component:VueForm2},{id:"selectable",name:"선택 가능한 표",component:VueForm3},{id:"actions",name:"행별 작업 표",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Table"),h('p',"데이터를 읽기 좋은 질서로 정리."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
