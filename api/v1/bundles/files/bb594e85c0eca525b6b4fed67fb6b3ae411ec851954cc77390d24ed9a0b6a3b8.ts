import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/resizable/default.vue';
import VueForm1 from './components/vue-sfc/resizable/editor.vue';
import VueForm2 from './components/vue-sfc/resizable/preview.vue';
import VueForm3 from './components/vue-sfc/resizable/vertical.vue';
import VueForm4 from './components/vue-sfc/resizable/comparison.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"editor",name:"편집기 분할",component:VueForm1},{id:"preview",name:"실시간 미리 보기",component:VueForm2},{id:"vertical",name:"세로 패널 조절",component:VueForm3},{id:"comparison",name:"비교 패널",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Resizable"),h('p',"사용자가 넓히는 작업 영역."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
