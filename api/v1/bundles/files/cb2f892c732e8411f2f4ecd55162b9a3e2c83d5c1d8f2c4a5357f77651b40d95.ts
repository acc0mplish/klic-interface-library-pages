const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"mega-docs",name:"문서 메가 메뉴",component:VueForm1},{id:"icon-directory",name:"아이콘 탐색 디렉터리",component:VueForm2},{id:"resource-columns",name:"그룹별 리소스",component:VueForm3},{id:"featured",name:"추천 콘텐츠 탐색",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Navigation Menu"),h('p',"주요 섹션으로 이어지는 분명한 입구."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
