import VueForm0 from './components/vue-sfc/separator/default.vue';
import VueForm1 from './components/vue-sfc/separator/labeled.vue';
import VueForm2 from './components/vue-sfc/separator/vertical.vue';
import VueForm3 from './components/vue-sfc/separator/content.vue';
import VueForm4 from './components/vue-sfc/separator/timeline-date.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"labeled",name:"라벨 구분선",component:VueForm1},{id:"vertical",name:"수직 도구 구분",component:VueForm2},{id:"content",name:"콘텐츠 구획",component:VueForm3},{id:"timeline-date",name:"날짜 구획",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Separator"),h('p',"정보 사이에 필요한 쉼표."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
