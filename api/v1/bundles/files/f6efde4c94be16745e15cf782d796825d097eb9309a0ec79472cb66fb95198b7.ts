import {createApp,defineComponent,h,ref} from 'vue';
import './styles.css';
import './brand.css';
import './component-expansion.css';
import './component-variants-examples.css';
import './component-families.css';
import './affect-components.css';
import './component-structure.css';
import './terminal-components.css';
import './fonts.css';
import VueForm0 from './components/vue-sfc/kbd/default.vue';
import VueForm1 from './components/vue-sfc/kbd/shortcut.vue';
import VueForm2 from './components/vue-sfc/kbd/help-dialog.vue';
import VueForm3 from './components/vue-sfc/kbd/inline-hint.vue';
import VueForm4 from './components/vue-sfc/kbd/navigation-guide.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"shortcut",name:"기본 단축키",component:VueForm1},{id:"help-dialog",name:"단축키 도움말",component:VueForm2},{id:"inline-hint",name:"입력 옆 힌트",component:VueForm3},{id:"navigation-guide",name:"키 탐색 안내",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Kbd"),h('p',"조작 방법을 작고 분명하게 안내."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
