import VueForm1 from './components/vue-sfc/input/contact.vue';
import VueForm2 from './components/vue-sfc/input/quick-add.vue';
import VueForm3 from './components/vue-sfc/input/url.vue';
import VueForm4 from './components/vue-sfc/input/readonly-token.vue';
const choices=[{id:"default",name:"KLIC 기본형",component:VueForm0},{id:"contact",name:"연락처 입력",component:VueForm1},{id:"quick-add",name:"빠른 항목 추가",component:VueForm2},{id:"url",name:"주소 입력",component:VueForm3},{id:"readonly-token",name:"읽기 전용 키",component:VueForm4}];
const selected=ref(new URLSearchParams(location.search).get('form')||choices[0]?.id);
const App=defineComponent({setup(){return()=>{const choice=choices.find(item=>item.id===selected.value)||choices[0];return h('main',{class:'cf-detail klic-vue-component-workspace'},[h('h1',"Input"),h('p',"정보를 담는 가장 기본적인 공간."),h('nav',{'aria-label':'Component forms'},choices.map(item=>h('button',{type:'button','aria-pressed':String(item.id===selected.value),onClick:()=>selected.value=item.id},item.name))),h('div',{class:'cf-canvas'},h(choice.component))]);}}});
createApp(App).mount('#app');
